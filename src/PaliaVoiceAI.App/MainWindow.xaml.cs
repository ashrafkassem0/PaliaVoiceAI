using System.Collections.ObjectModel;
using System.Globalization;
using System.Windows;
using System.Windows.Controls;
using PaliaVoiceAI.Audio;
using PaliaVoiceAI.Capture;
using PaliaVoiceAI.Core;
using PaliaVoiceAI.OCR;
using PaliaVoiceAI.TTS;

namespace PaliaVoiceAI.App;

public partial class MainWindow : Window
{
    private readonly AudioPlayer _player = new();
    private readonly ObservableCollection<BenchmarkRecord> _records = new();
    private readonly ITtsEngine _engine = new MockTtsEngine();
    private readonly DialogueCapture _capture = new();
    private readonly WindowsOcrEngine _ocr = new();
    private CancellationTokenSource? _generateCts;
    private CancellationTokenSource? _monitorCts;
    private byte[]? _lastAudio;

    public MainWindow()
    {
        InitializeComponent();
        ResultsGrid.ItemsSource = _records;
        LoadBenchmarks();
        LoadCaptureSettings();
    }

    private async void Generate_Click(object sender, RoutedEventArgs e)
    {
        if (!TryReadSpeechRequest(out var text, out var voice, out var threads))
            return;

        _generateCts?.Dispose();
        _generateCts = new CancellationTokenSource();
        var token = _generateCts.Token;
        GenerateButton.IsEnabled = false;
        try
        {
            await _engine.InitializeAsync(new TtsOptions(TtsBackend.Mock, threads, 1), token);
            var result = await _engine.GenerateAsync(text, voice, token);
            _lastAudio = result.AudioBytes;
            _records.Insert(0, new BenchmarkRecord(
                DateTimeOffset.Now,
                result.EngineName,
                TtsBackend.Mock.ToString(),
                threads,
                text.Length,
                result.GenerationTime.TotalMilliseconds,
                result.AudioDuration.TotalMilliseconds,
                result.RealTimeFactor));
            BenchmarkCsv.Write(AppPaths.BenchmarksCsv, _records);
            StatusText.Text = $"Generated by {result.EngineName}. Generation: {result.GenerationTime.TotalMilliseconds:N0} ms · Audio: {result.AudioDuration.TotalMilliseconds:N0} ms · RTF: {result.RealTimeFactor:N3}. Mock output is silent.";
        }
        catch (OperationCanceledException)
        {
            StatusText.Text = "Generation cancelled.";
        }
        catch (Exception ex)
        {
            StatusText.Text = ex.Message;
        }
        finally
        {
            GenerateButton.IsEnabled = true;
        }
    }

    private void Play_Click(object sender, RoutedEventArgs e)
    {
        if (_lastAudio is null)
        {
            StatusText.Text = "Generate audio first.";
            return;
        }

        try
        {
            _player.PlayWav(_lastAudio);
            StatusText.Text = "Playback started (silent mock WAV).";
        }
        catch (Exception ex)
        {
            StatusText.Text = ex.Message;
        }
    }

    private void Stop_Click(object sender, RoutedEventArgs e)
    {
        _generateCts?.Cancel();
        _player.Stop();
        StatusText.Text = "Playback stopped.";
    }

    private bool TryReadSpeechRequest(out string text, out string voice, out int threads)
    {
        text = DialogueBox.Text.Trim();
        voice = string.Empty;
        threads = 3;
        if (text.Length == 0)
        {
            StatusText.Text = "Enter dialogue first.";
            return false;
        }

        if (BackendBox.SelectedIndex != 0)
        {
            StatusText.Text = "CPU and CUDA are not connected yet. Choose Mock (pipeline test).";
            return false;
        }

        if (VoiceBox.SelectedItem is not ComboBoxItem voiceItem || voiceItem.Content is not string voiceId)
        {
            StatusText.Text = "Choose a voice.";
            return false;
        }

        if (ThreadsBox.SelectedItem is not ComboBoxItem threadItem ||
            !int.TryParse(threadItem.Content?.ToString(), NumberStyles.Integer, CultureInfo.InvariantCulture, out threads))
        {
            StatusText.Text = "Choose a thread count.";
            return false;
        }

        voice = voiceId;
        return true;
    }

    private void LoadBenchmarks()
    {
        try
        {
            foreach (var record in BenchmarkCsv.Read(AppPaths.BenchmarksCsv))
                _records.Add(record);
        }
        catch (Exception ex)
        {
            var backup = BenchmarkCsv.Quarantine(AppPaths.BenchmarksCsv);
            StatusText.Text = $"Could not read the benchmark history ({ex.Message}). It was moved to {backup}.";
        }
    }

    protected override void OnClosed(EventArgs e)
    {
        _monitorCts?.Cancel();
        _generateCts?.Cancel();
        TrySaveCaptureSettings();
        _capture.Release();
        _player.Dispose();
        base.OnClosed(e);
    }
}
