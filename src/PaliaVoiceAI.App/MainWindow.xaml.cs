using System.Collections.ObjectModel;
using System.Globalization;
using System.IO;
using System.Text;
using System.Windows;
using PaliaVoiceAI.Audio;
using PaliaVoiceAI.Core;
using PaliaVoiceAI.TTS;

namespace PaliaVoiceAI.App;

public partial class MainWindow : Window
{
    private readonly AudioPlayer _player = new();
    private readonly ObservableCollection<BenchmarkRecord> _records = new();
    private readonly ITtsEngine _engine = new MockTtsEngine();
    private byte[]? _lastAudio;

    public MainWindow()
    {
        InitializeComponent();
        ResultsGrid.ItemsSource = _records;
    }

    private async void Generate_Click(object sender, RoutedEventArgs e)
    {
        var text = DialogueBox.Text.Trim();
        if (text.Length == 0) { StatusText.Text = "Enter dialogue first."; return; }

        GenerateButton.IsEnabled = false;
        try
        {
            var threads = int.Parse(((System.Windows.Controls.ComboBoxItem)ThreadsBox.SelectedItem).Content.ToString()!, CultureInfo.InvariantCulture);
            var voice = ((System.Windows.Controls.ComboBoxItem)VoiceBox.SelectedItem).Content.ToString()!;
            await _engine.InitializeAsync(new TtsOptions(TtsBackend.Mock, threads, 1));
            var result = await _engine.GenerateAsync(text, voice);
            _lastAudio = result.AudioBytes;
            _records.Insert(0, new BenchmarkRecord(DateTimeOffset.Now, result.EngineName, "Mock", threads,
                text.Length, result.GenerationTime.TotalMilliseconds, result.AudioDuration.TotalMilliseconds, result.RealTimeFactor));
            SaveCsv(_records);
            StatusText.Text = $"Generated by {result.EngineName}. Generation: {result.GenerationTime.TotalMilliseconds:N0} ms · Audio: {result.AudioDuration.TotalMilliseconds:N0} ms · RTF: {result.RealTimeFactor:N3}. Mock output is silent.";
        }
        catch (Exception ex) { StatusText.Text = ex.Message; }
        finally { GenerateButton.IsEnabled = true; }
    }

    private void Play_Click(object sender, RoutedEventArgs e)
    {
        if (_lastAudio is null) { StatusText.Text = "Generate audio first."; return; }
        try { _player.PlayWav(_lastAudio); StatusText.Text = "Playback started (silent mock WAV)."; }
        catch (Exception ex) { StatusText.Text = ex.Message; }
    }

    private void Stop_Click(object sender, RoutedEventArgs e) { _player.Stop(); StatusText.Text = "Playback stopped."; }

    private static void SaveCsv(IEnumerable<BenchmarkRecord> records)
    {
        var dir = Path.Combine(Environment.GetFolderPath(Environment.SpecialFolder.LocalApplicationData), "PaliaVoiceAI");
        Directory.CreateDirectory(dir);
        var path = Path.Combine(dir, "benchmarks.csv");
        var lines = new List<string> { "Timestamp,Engine,Backend,Threads,TextLength,GenerationMs,AudioDurationMs,RTF" };
        lines.AddRange(records.Select(r => string.Join(",",
            r.Timestamp.ToString("O", CultureInfo.InvariantCulture), Csv(r.Engine), r.Backend,
            r.Threads, r.TextLength, r.GenerationMs.ToString("F2", CultureInfo.InvariantCulture),
            r.AudioDurationMs.ToString("F2", CultureInfo.InvariantCulture), r.RealTimeFactor.ToString("F4", CultureInfo.InvariantCulture))));
        File.WriteAllLines(path, lines, Encoding.UTF8);
    }

    private static string Csv(string value) => "\"" + value.Replace("\"", "\"\"") + "\"";

    protected override void OnClosed(EventArgs e)
    {
        _player.Dispose();
        _engine.DisposeAsync().AsTask().GetAwaiter().GetResult();
        base.OnClosed(e);
    }
}
