using System.Collections.ObjectModel;
using System.Globalization;
using System.IO;
using System.Windows;
using System.Windows.Controls;
using PaliaVoiceAI.Audio;
using PaliaVoiceAI.Capture;
using PaliaVoiceAI.Core;
using PaliaVoiceAI.OCR;
using PaliaVoiceAI.TTS;

namespace PaliaVoiceAI.App;

public partial class MainWindow : Window
{
    private readonly AudioPlayer _player = new();
    private readonly ObservableCollection<BenchmarkRecord> _records = new();
    private readonly MockTtsEngine _mock = new();
    private readonly KokoroTtsEngine _kokoro = new();
    private readonly DialogueCapture _capture = new();
    private readonly WindowsOcrEngine _ocr = new();
    private readonly SpeechCache _cache = new(AppPaths.SpeechCache);
    private readonly SessionLog _log = new(AppPaths.Logs);
    private readonly SpeechQueue _speech;
    private AppSettings _appSettings = new();
    private bool _settingsReady;
    private CancellationTokenSource? _monitorCts;
    private byte[]? _lastAudio;
    private int _speechBusy;
    private int _speakSerial;

    public MainWindow()
    {
        _speech = new SpeechQueue(_cache, PrepareSpeechAsync, _player);
        InitializeComponent();
        ResultsGrid.ItemsSource = _records;
        _kokoro.Progress += message => Dispatcher.Invoke(() => StatusText.Text = message);
        LoadBenchmarks();
        LoadCaptureSettings();
        LoadVoiceLibrary();
        LoadAppSettings();
    }

    private async void Generate_Click(object sender, RoutedEventArgs e)
    {
        if (!TryReadSpeechRequest(out var text, out var voice, out var threads, out var backend))
            return;

        await SpeakAsync(text, voice, threads, backend, 1f, play: true, speaker: voice);
    }

    private async Task SpeakAsync(string text, string voice, int threads, TtsBackend backend, float speed, bool play, string speaker)
    {
        var serial = Interlocked.Increment(ref _speakSerial);
        Interlocked.Increment(ref _speechBusy);
        GenerateButton.IsEnabled = false;
        PreviewVoiceButton.IsEnabled = false;
        var request = new SpeechRequest(text, voice, speed, backend, threads, play);
        try
        {
            if (_speech.IsBusy || _speech.PendingCount > 0)
                StatusText.Text = "Waiting for the current line to finish.";

            var delivery = await _speech.SubmitAsync(request);
            _lastAudio = delivery.Audio;
            var shownRtf = delivery.AudioDuration.TotalSeconds <= 0
                ? 0
                : delivery.GenerationTime.TotalSeconds / delivery.AudioDuration.TotalSeconds;
            _log.Timing(new SpeechTiming(
                delivery.Backend,
                delivery.VoiceId,
                threads,
                delivery.GenerationTime.TotalMilliseconds,
                delivery.AudioDuration.TotalMilliseconds,
                shownRtf,
                delivery.FromCache,
                text.Length));
            if (!delivery.FromCache)
            {
                var rtf = delivery.AudioDuration.TotalSeconds <= 0
                    ? 0
                    : delivery.GenerationTime.TotalSeconds / delivery.AudioDuration.TotalSeconds;
                _records.Insert(0, new BenchmarkRecord(
                    DateTimeOffset.Now,
                    delivery.EngineName,
                    delivery.Backend,
                    threads,
                    text.Length,
                    delivery.GenerationTime.TotalMilliseconds,
                    delivery.AudioDuration.TotalMilliseconds,
                    rtf));
                BenchmarkCsv.Write(AppPaths.BenchmarksCsv, _records);
            }

            RememberLine(speaker, text, delivery.Audio);
            if (serial != Volatile.Read(ref _speakSerial))
                return;

            if (delivery.FromCache)
            {
                var pace = delivery.Pace.ToString("0.00", CultureInfo.InvariantCulture);
                StatusText.Text = $"Stored line for {delivery.VoiceId} at pace {pace}. No new generation. Audio: {delivery.AudioDuration.TotalMilliseconds:N0} ms.";
                return;
            }

            var silent = delivery.Backend == nameof(TtsBackend.Mock) ? " Mock output is silent." : string.Empty;
            var fallback = backend == TtsBackend.Cuda && delivery.Backend == nameof(TtsBackend.Cpu)
                ? " CUDA was not available, so this run used CPU."
                : string.Empty;
            StatusText.Text = $"Generated by {delivery.EngineName}. Generation: {delivery.GenerationTime.TotalMilliseconds:N0} ms · Audio: {delivery.AudioDuration.TotalMilliseconds:N0} ms · RTF: {shownRtf:N3}.{silent}{fallback}";
        }
        catch (OperationCanceledException)
        {
            if (serial == Volatile.Read(ref _speakSerial))
                StatusText.Text = "Speech stopped.";
        }
        catch (Exception ex)
        {
            _log.Error("speech", ex.GetType().Name);
            if (serial == Volatile.Read(ref _speakSerial))
                StatusText.Text = ex.Message;
        }
        finally
        {
            if (Interlocked.Decrement(ref _speechBusy) == 0)
            {
                GenerateButton.IsEnabled = true;
                PreviewVoiceButton.IsEnabled = true;
            }
        }
    }

    private async Task<PreparedSpeech> PrepareSpeechAsync(SpeechRequest request, CancellationToken token)
    {
        if (request.Backend == TtsBackend.Mock)
        {
            var mockIdentity = SpeechIdentity.Create(request.Text, request.VoiceId, request.Pace, "mock", MockTtsEngine.EngineVersion);
            return new PreparedSpeech(mockIdentity, async cancellationToken =>
            {
                await _mock.InitializeAsync(new TtsOptions(TtsBackend.Mock, request.Threads, 1), cancellationToken).ConfigureAwait(false);
                return await _mock.GenerateAsync(mockIdentity.Text, mockIdentity.VoiceId, cancellationToken, mockIdentity.Pace).ConfigureAwait(false);
            });
        }

        var path = KokoroModelLocator.Find();
        if (path is null)
        {
            await _kokoro.InitializeAsync(new TtsOptions(request.Backend, request.Threads, 1), token).ConfigureAwait(false);
            path = KokoroModelLocator.Find();
            if (path is null)
                throw new System.IO.FileNotFoundException("Kokoro model was not found after download.", AppPaths.KokoroOnnx);
        }

        var identity = SpeechIdentity.Create(request.Text, request.VoiceId, request.Pace, ModelFileHash.Sha256(path), KokoroTtsEngine.EngineVersion);
        return new PreparedSpeech(identity, async cancellationToken =>
        {
            await _kokoro.InitializeAsync(new TtsOptions(request.Backend, request.Threads, 1), cancellationToken).ConfigureAwait(false);
            return await _kokoro.GenerateAsync(identity.Text, identity.VoiceId, cancellationToken, identity.Pace).ConfigureAwait(false);
        });
    }

    private void Play_Click(object sender, RoutedEventArgs e)
    {
        if (_lastAudio is null)
        {
            StatusText.Text = "Generate audio first.";
            return;
        }

        Interlocked.Increment(ref _speakSerial);
        _speech.Stop();
        try
        {
            _player.PlayWav(_lastAudio);
            StatusText.Text = "Playback started.";
        }
        catch (Exception ex)
        {
            _log.Error("playback", ex.GetType().Name);
            StatusText.Text = ex.Message;
        }
    }

    private void Stop_Click(object sender, RoutedEventArgs e)
    {
        Interlocked.Increment(ref _speakSerial);
        _speech.Stop();
        StatusText.Text = "Speech stopped.";
    }

    private void ClearCache_Click(object sender, RoutedEventArgs e)
    {
        var removed = _cache.DeleteAll();
        var message = removed == 0
            ? "No stored lines to delete."
            : $"Deleted {removed} stored {(removed == 1 ? "line" : "lines")}.";
        CacheStatus.Text = message;
        StatusText.Text = message;
    }

    private bool TryReadSpeechRequest(out string text, out string voice, out int threads, out TtsBackend backend)
    {
        text = DialogueBox.Text.Trim();
        voice = string.Empty;
        threads = 3;
        backend = BackendBox.SelectedIndex switch
        {
            2 => TtsBackend.Cuda,
            1 => TtsBackend.Cpu,
            _ => TtsBackend.Mock
        };
        if (text.Length == 0)
        {
            StatusText.Text = "Enter dialogue first.";
            return false;
        }

        if (VoiceBox.SelectedItem is not ComboBoxItem voiceItem || voiceItem.Tag is not string voiceId)
        {
            StatusText.Text = "Choose a voice.";
            return false;
        }

        if (ThreadsBox.SelectedItem is not ComboBoxItem threadItem ||
            !int.TryParse(threadItem.Content?.ToString(), NumberStyles.Integer, CultureInfo.InvariantCulture, out threads))
        {
            StatusText.Text = "Choose a thread count.";
            return false;
        }

        voice = voiceId;
        return true;
    }

    private void LoadBenchmarks()
    {
        try
        {
            foreach (var record in BenchmarkCsv.Read(AppPaths.BenchmarksCsv))
                _records.Add(record);
        }
        catch (Exception ex)
        {
            _log.Error("benchmark", ex.GetType().Name);
            var backup = BenchmarkCsv.Quarantine(AppPaths.BenchmarksCsv);
            StatusText.Text = $"Could not read the benchmark history ({ex.Message}). It was moved to {backup}.";
        }
    }

    private void LoadAppSettings()
    {
        _appSettings = AppSettingsStore.Load();
        BackendBox.SelectedIndex = _appSettings.BackendKind switch
        {
            TtsBackend.Mock => 0,
            TtsBackend.Cuda => 2,
            _ => 1
        };
        ThreadsBox.SelectedIndex = _appSettings.ClampedThreads switch
        {
            2 => 0,
            4 => 2,
            _ => 1
        };
        SelectStudioVoice(_appSettings.StudioVoiceId);
        VolumeSlider.Value = _appSettings.VolumePercent;
        VolumeReadout.Text = _appSettings.VolumePercent.ToString(CultureInfo.InvariantCulture) + "%";
        _player.Volume = _appSettings.VolumeLevel;
        _settingsReady = true;
    }

    private void SelectStudioVoice(string voiceId)
    {
        for (var index = 0; index < VoiceBox.Items.Count; index++)
        {
            if (VoiceBox.Items[index] is ComboBoxItem item &&
                item.Tag is string id &&
                string.Equals(id, voiceId, StringComparison.OrdinalIgnoreCase))
            {
                VoiceBox.SelectedIndex = index;
                return;
            }
        }

        VoiceBox.SelectedIndex = 0;
    }

    private void EngineChoice_Changed(object sender, SelectionChangedEventArgs e) => RememberAppSettings();

    private void VolumeSlider_ValueChanged(object sender, RoutedPropertyChangedEventArgs<double> e) => RememberAppSettings();

    private void RememberAppSettings()
    {
        if (!_settingsReady)
            return;

        var (threads, backend) = ReadEngineChoice();
        var voice = _appSettings.StudioVoiceId;
        if (VoiceBox.SelectedItem is ComboBoxItem item && item.Tag is string id)
            voice = id;
        _appSettings = new AppSettings
        {
            Backend = backend.ToString(),
            Threads = threads,
            StudioVoiceId = voice,
            VolumePercent = (int)Math.Round(VolumeSlider.Value)
        }.Normalized();
        VolumeReadout.Text = _appSettings.VolumePercent.ToString(CultureInfo.InvariantCulture) + "%";
        _player.Volume = _appSettings.VolumeLevel;
        try
        {
            AppSettingsStore.Save(_appSettings);
        }
        catch (Exception ex) when (ex is IOException or UnauthorizedAccessException)
        {
            _log.Error("settings", ex.GetType().Name);
            StatusText.Text = "Could not save settings.";
        }
    }

    public void ReportFailure(string exceptionType)
    {
        StatusText.Text = $"Something failed ({exceptionType}). It was logged. The app is still open.";
    }

    protected override void OnClosed(EventArgs e)
    {
        _monitorCts?.Cancel();
        RememberAppSettings();
        TrySaveCaptureSettings();
        _capture.Release();
        _speech.Dispose();
        _player.Dispose();
        _kokoro.DisposeAsync().AsTask().GetAwaiter().GetResult();
        _mock.DisposeAsync().AsTask().GetAwaiter().GetResult();
        base.OnClosed(e);
    }
}
